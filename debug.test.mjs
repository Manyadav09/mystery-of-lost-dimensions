import { chromium } from 'playwright-core';
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', e => console.log('PAGEERROR:', e.message));
await page.goto('http://127.0.0.1:4181/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.getByText('Begin the Expedition').click();
await page.waitForTimeout(1500);
const veil = page.getByText('CLICK TO CONTINUE');
if (await veil.count()) await veil.click();
await page.waitForTimeout(400);
const before = await page.evaluate(() => window.__mld?.pos());
const lockedBefore = await page.evaluate(() => window.__mld?.locked());
await page.keyboard.down('KeyW');
await page.waitForTimeout(1500);
const keysDuring = await page.evaluate(() => window.__mld?.keys());
await page.keyboard.up('KeyW');
const after = await page.evaluate(() => window.__mld?.pos());
console.log(JSON.stringify({ before, lockedBefore, keysDuring, after }, null, 1));
await browser.close();
